/** Mechanical, immutable parser capture for the offline format-3 -> format-4 conversion. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const sourceRoot = resolve(root, 'packages/contracts/src');
const targetRoot = resolve(sourceRoot, 'generated/upgrade-v3');
const revision = '12e5b87';
const loop = await readFile(resolve(sourceRoot, 'loop.ts'), 'utf8');
if (!loop.includes('schemaVersion: z.literal(3)') || !loop.includes('formatVersion: z.literal(3)'))
  throw new Error(
    'Capture only the frozen format-3 source; do not recapture changing current schemas',
  );
const pending = [
  'loop.ts',
  'events.ts',
  'evaluation.ts',
  'run.ts',
  'thread.ts',
  'trigger-integrations.ts',
];
const captured = new Map();
while (pending.length) {
  const name = pending.pop();
  if (captured.has(name)) continue;
  const source = await readFile(resolve(sourceRoot, name), 'utf8');
  captured.set(name, source);
  for (const match of source.matchAll(/from\s+['"]\.\/([^'"]+)\.js['"]/g))
    pending.push(match[1] + '.ts');
}
const sources = [...captured].sort(([a], [b]) => a.localeCompare(b));
const hashes = Object.fromEntries(
  sources.map(([name, source]) => [name, createHash('sha256').update(source).digest('hex')]),
);
let provenance;
try {
  provenance = JSON.parse(await readFile(resolve(targetRoot, 'provenance.json'), 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  if (git('rev-parse', 'HEAD') !== git('rev-parse', revision))
    throw new Error(`First format-3 capture requires HEAD at ${revision}`, { cause: error });
  // HEAD alone does not exclude uncommitted source edits on the capture revision.
  provenance = {
    revision,
    hashes: Object.fromEntries(
      sources.map(([name]) => [
        name,
        createHash('sha256')
          .update(
            execFileSync('git', ['show', `${revision}:packages/contracts/src/${name}`], {
              cwd: root,
            }),
          )
          .digest('hex'),
      ]),
    ),
  };
}
if (
  provenance.revision !== revision ||
  Object.keys(provenance.hashes).length !== sources.length ||
  Object.entries(hashes).some(([name, digest]) => provenance.hashes[name] !== digest)
)
  throw new Error(`Refusing to recapture sources that differ from the ${revision} provenance`);
// Verify the complete import closure before creating or overwriting any capture files.
await mkdir(targetRoot, { recursive: true });
for (const [name, source] of sources) {
  const digest = hashes[name];
  await writeFile(
    resolve(targetRoot, name),
    `// GENERATED by tooling/scripts/freeze-upgrade-v3.mjs from ${revision}; source SHA-256 ${digest}.\n` +
      '// Offline migration only. Never import this parser for runtime admission.\n' +
      source,
  );
}
await writeFile(
  resolve(targetRoot, 'provenance.json'),
  JSON.stringify({ revision, hashes }, null, 2) + '\n',
);
