import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';

const repo = 'C:/Users/98jak/.codex/worktrees/gg-20261115-runtime/GraphGoblin';
const batch = 'C:/Users/98jak/graphgoblin-qa/2026-11-13-aidlc-batch';
const dir = path.join(batch, 'audit-484-astra-scan2');
const head = '08651317c485062eb90367e1df3f7632f8e1a6c7';
const target = '15ce9a1dd12e87b7f7cb5f853aaecf68d6188afd';
const merge = '98d2bc2c473d3167a39ae966f9dfb9e2f00904fe';
const tree = 'c5d6d7f505e52b5ccf07b4bcb791777761dc45df';
const initial = JSON.parse(fs.readFileSync(path.join(dir, 'independent-integrity.json')));
const github = JSON.parse(fs.readFileSync(path.join(dir, 'final-connector-readbacks.json')));
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const git = args => execFileSync('git', args, { cwd: repo, env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' }, encoding: 'utf8' }).trim();
const output = { at: new Date().toISOString(), runtime: process.version, head: git(['rev-parse', 'HEAD']), tree: git(['rev-parse', 'HEAD^{tree}']), mergeBase: git(['merge-base', target, 'HEAD']), status: git(['status', '--porcelain=v1', '--untracked-files=all']), indexSHA256: hash(fs.readFileSync(git(['rev-parse', '--path-format=absolute', '--git-path', 'index']))), sourceFiles: [] };
assert.equal(output.runtime, 'v22.23.4');
assert.equal(output.head, head);
assert.equal(output.tree, tree);
assert.equal(output.mergeBase, target);
assert.equal(output.status, '');
assert.equal(output.indexSHA256, initial.before.indexSHA256);
for (const source of initial.sourceRecords) {
  const digest = hash(fs.readFileSync(path.join(repo, source.path)));
  assert.equal(digest, source.sha256, source.path);
  output.sourceFiles.push({ path: source.path, sha256: digest });
}
output.diffCheck = git(['diff', '--check', target, 'HEAD', '--', '.', ':!docs/qa']);
assert.equal(output.diffCheck, '');
output.remoteRefsRaw = git(['ls-remote', 'origin', 'refs/heads/main', 'refs/pull/484/head', 'refs/pull/484/merge']);
const refs = Object.fromEntries(output.remoteRefsRaw.split(/\r?\n/).map(line => { const [sha, ref] = line.split(/\s+/); return [ref, sha]; }));
assert.deepEqual(refs, { 'refs/heads/main': target, 'refs/pull/484/head': head, 'refs/pull/484/merge': merge });
const pr = github.pr.structuredContent;
assert.equal(pr.head_sha, head);
assert.equal(pr.base_sha, target);
assert.equal(pr.merge_commit_sha, merge);
assert.equal(pr.state, 'open');
assert.equal(pr.merged, false);
assert.equal(pr.commits, 2);
assert.equal(pr.changed_files, 343);
output.pr = { at: github.at, state: pr.state, merged: pr.merged, draft: pr.draft, mergeable: pr.mergeable, head: pr.head_sha, base: pr.base_sha, merge: pr.merge_commit_sha, commits: pr.commits, changedFiles: pr.changed_files };
const comment = github.comments.structuredContent.comments.find(c => c.url.endsWith('#issuecomment-6895278204'));
assert.ok(comment, 'Claude review publication is still present');
const fullClaude = fs.readFileSync(path.join(batch, 'review-484-opus-scan1/full-report.md'));
const normalise = value => value.replace(/\r\n/g, '\n').replace(/\n+$/, '');
assert.equal(hash(fullClaude), '8804954db1e294f68493fe0a16f40e7a9ac7f9f73afbebd5b7e8535c9ca53b55');
assert.equal(normalise(comment.body), normalise(fullClaude.toString('utf8')));
output.claudeComment = { url: comment.url, reportSHA256: hash(fullClaude), normalisation: 'CRLF to LF and terminal LF characters removed; local has one, GitHub has two', fullTextMatches: true };
output.completedAt = new Date().toISOString();
output.pass = true;
fs.writeFileSync(path.join(dir, 'final-identity.json'), JSON.stringify(output, null, 2) + '\n');
process.stdout.write(JSON.stringify({ pass: true, at: output.completedAt, sourceFiles: output.sourceFiles.length, head, target, tree, indexSHA256: output.indexSHA256, claudeCommentMatches: true }) + '\n');
