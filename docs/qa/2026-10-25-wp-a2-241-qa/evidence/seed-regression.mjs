import { cp, readFile, writeFile, mkdtemp } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createHash } from 'node:crypto';
const evidence = new URL('.', import.meta.url);
const source = resolve('apps/web/dist');
const destination = await mkdtemp(join(tmpdir(), 'gg-wpa2-qa-seed-'));
const outputRoot = await mkdtemp(join(tmpdir(), 'gg-wpa2-qa-output-'));
const safe = path => path.replace(process.env.USERPROFILE, '%USERPROFILE%');
await cp(source, destination, {recursive:true});
const original = await readFile(join(source,'index.html'));
const before = await readFile(join(destination,'index.html'),'utf8');
if (!before.includes('</head>')) throw new Error('index.html has no head closing tag');
const after = before.replace('</head>','<style data-qa-seed="241">h1{display:none!important}</style></head>');
await writeFile(join(destination,'index.html'), after);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const normalAfter = await readFile(join(source,'index.html'));
if (!original.equals(normalAfter)) throw new Error('normal build changed during seeding');
const result = {source:source.replace(process.env.USERPROFILE,'%USERPROFILE%'),destination:destination.replace(process.env.USERPROFILE,'%USERPROFILE%'),mutation:'hide h1 headings through a style inserted in disposable index.html',originalSha256:hash(original),seedSha256:hash(Buffer.from(after)),normalIndexUnchanged:true,outputFolder:safe(join(outputRoot,'seed-results')),htmlFolder:safe(join(outputRoot,'seed-report')),controlOutputFolder:safe(join(outputRoot,'control-results')),controlHtmlFolder:safe(join(outputRoot,'control-report'))};
await writeFile(new URL('seed-manifest.json',evidence),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
