import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root = 'C:/Users/98jak/.codex/worktrees/gg-20261114-save-publish/GraphGoblin';
const folder = 'C:/Users/98jak/graphgoblin-qa/2026-11-13-aidlc-batch/review-237';
const git = (...args) => execFileSync('git', ['-C', root, ...args], { maxBuffer: 20 * 1024 * 1024, env: { ...process.env, GIT_OPTIONAL_LOCKS: '0' } });
const line = (...args) => git(...args).toString().trim();
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const parent = '1dcee36b16cc4662e8acb691e9166aff52949ad9';
if (line('rev-parse', 'HEAD') !== parent || line('diff', '--cached', '--name-only')) throw new Error('Unexpected HEAD/index');
const records = readFileSync(`${folder}/ui-correction/logs/source-hashes-final.txt`, 'utf8').trim().split(/\r?\n/).map(row => {
  const match = /^([a-f0-9]{64}) \*(.+)$/.exec(row);
  if (!match) throw new Error('Malformed source manifest');
  return { path: match[2], sha256: match[1] };
});
if (records.length !== 8) throw new Error('Unexpected scope');
const changed = line('diff', '--name-only').split(/\r?\n/).sort();
if (JSON.stringify(changed) !== JSON.stringify(records.map(f => f.path).sort()) || line('ls-files', '--others', '--exclude-standard')) throw new Error('Changed path set differs');
for (const file of records) if (sha(readFileSync(`${root}/${file.path}`)) !== file.sha256) throw new Error(`Working source changed: ${file.path}`);
git('diff', '--check');
git('add', '--', ...records.map(f => f.path));
for (const file of records) if (sha(git('show', `:${file.path}`)) !== file.sha256) throw new Error(`Staged source mismatch: ${file.path}`);
git('commit', '-q', '-m', 'Resolve publish readback conflicts and stale validation');
const head = line('rev-parse', 'HEAD'), tree = line('rev-parse', 'HEAD^{tree}');
for (const file of records) if (sha(git('show', `${head}:${file.path}`)) !== file.sha256) throw new Error(`Committed source mismatch: ${file.path}`);
if (line('status', '--porcelain')) throw new Error('Not clean after freeze');
const result = { at: new Date().toISOString(), parent, head, tree, files: records, scope: 'Eight source/test/docs correction files only; no build or publication' };
writeFileSync(`${folder}/source-correction-freeze.json`, JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result));
